// Generate new Patient ID
export const generatePatientId = (): string => {
  const lastId = mockPatients.length > 0 
    ? parseInt(mockPatients[mockPatients.length - 1].id.replace('P', ''))
    : 0;
  return `P${String(lastId + 1).padStart(3, '0')}`;
};

// Generate new Token Number
export const generateTokenNumber = (queueType: 'opd' | 'specialist'): string => {
  const prefix = queueType === 'opd' ? 'A' : 'B';
  const tokens = mockQueueTokens.filter(t => t.tokenNumber.startsWith(prefix));
  const lastNum = tokens.length > 0 
    ? parseInt(tokens[tokens.length - 1].tokenNumber.replace(prefix, ''))
    : 0;
  return `${prefix}${String(lastNum + 1).padStart(3, '0')}`;
};
